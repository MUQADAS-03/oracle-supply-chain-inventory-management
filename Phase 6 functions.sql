DECLARE
    V_VALUE NUMBER;
    V_AVG   NUMBER;
    V_DAYS  NUMBER;
BEGIN
    V_VALUE := HRDB.FN_GET_STOCK_VALUE(1, 1);
    V_AVG   := HRDB.FN_AVG_DAILY_CONSUMPTION(1, 1);
    V_DAYS  := HRDB.FN_DAYS_OF_SUPPLY(1, 1);

    DBMS_OUTPUT.PUT_LINE('Stock Value          : ' || V_VALUE);
    DBMS_OUTPUT.PUT_LINE('Avg Daily Consumption: ' || V_AVG);
    DBMS_OUTPUT.PUT_LINE('Days of Supply Left  : ' || V_DAYS);
END;
/

