--- 11. SALES_ORDER_DETAIL 
CREATE OR REPLACE PROCEDURE HRDB.PROC_ADD_SO_DETAIL (
    P_SO_ID        IN NUMBER,
    P_PRODUCT_ID   IN NUMBER,
    P_QTY          IN NUMBER,
    P_UNIT_PRICE   IN NUMBER,
    P_WAREHOUSE_ID IN NUMBER
)
AS
BEGIN
    INSERT INTO HRDB.SALES_ORDER_DETAIL (SO_ID, PRODUCT_ID, QUANTITY, UNIT_PRICE)
    VALUES (P_SO_ID, P_PRODUCT_ID, P_QTY, P_UNIT_PRICE);

    UPDATE HRDB.SALES_ORDER
    SET TOTAL_AMOUNT = NVL(TOTAL_AMOUNT, 0) + (P_QTY * P_UNIT_PRICE)
    WHERE SO_ID = P_SO_ID;

    -- Reuses the issue-stock procedure
    -- reduces real warehouse stock, referencing this sales order
    HRDB.PROC_ISSUE_STOCK(P_PRODUCT_ID, P_WAREHOUSE_ID, P_QTY, 'SALES_ORDER', P_SO_ID);

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Added ' || P_QTY || ' units of product ' || P_PRODUCT_ID || ' to SO ' || P_SO_ID);
END PROC_ADD_SO_DETAIL;
/

--- 12. LOW_STOCK_ALERT 
CREATE OR REPLACE PROCEDURE HRDB.PROC_UPDATE_ALERT_STATUS (
    P_ALERT_ID  IN NUMBER,
    P_STATUS    IN VARCHAR2   -- 'ACKNOWLEDGED' or 'RESOLVED'
)
AS
BEGIN
    UPDATE HRDB.LOW_STOCK_ALERT
    SET STATUS = P_STATUS
    WHERE ALERT_ID = P_ALERT_ID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'Alert ID ' || P_ALERT_ID || ' not found.');
    END IF;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Alert ' || P_ALERT_ID || ' updated to status: ' || P_STATUS);
END PROC_UPDATE_ALERT_STATUS;
/

