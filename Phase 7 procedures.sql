--- 6. STOCK - receive stock 
CREATE OR REPLACE PROCEDURE HRDB.PROC_RECEIVE_STOCK (
    P_PRODUCT_ID     IN NUMBER,
    P_WAREHOUSE_ID   IN NUMBER,
    P_QTY            IN NUMBER,
    P_UNIT_PRICE     IN NUMBER DEFAULT NULL,
    P_REFERENCE_TYPE IN VARCHAR2 DEFAULT 'MANUAL',
    P_REFERENCE_ID   IN NUMBER DEFAULT NULL
)
AS
    V_EXISTS NUMBER;
BEGIN
    IF P_QTY <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Quantity must be positive.');
    END IF;

    SELECT COUNT(*) INTO V_EXISTS FROM HRDB.STOCK
    WHERE PRODUCT_ID = P_PRODUCT_ID AND WAREHOUSE_ID = P_WAREHOUSE_ID;

    IF V_EXISTS = 0 THEN
        INSERT INTO HRDB.STOCK (PRODUCT_ID, WAREHOUSE_ID, QUANTITY_ON_HAND, LAST_UPDATED)
        VALUES (P_PRODUCT_ID, P_WAREHOUSE_ID, P_QTY, SYSDATE);
    ELSE
        UPDATE HRDB.STOCK
        SET QUANTITY_ON_HAND = QUANTITY_ON_HAND + P_QTY, LAST_UPDATED = SYSDATE
        WHERE PRODUCT_ID = P_PRODUCT_ID AND WAREHOUSE_ID = P_WAREHOUSE_ID;
    END IF;

    INSERT INTO HRDB.STOCK_TRANSACTION (
        PRODUCT_ID, WAREHOUSE_ID, TRANSACTION_TYPE, QUANTITY,
        TRANSACTION_DATE, REFERENCE_TYPE, REFERENCE_ID, UNIT_PRICE
    ) VALUES (
        P_PRODUCT_ID, P_WAREHOUSE_ID, 'IN', P_QTY, SYSDATE, P_REFERENCE_TYPE, P_REFERENCE_ID, P_UNIT_PRICE
    );

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Received ' || P_QTY || ' units of product ' || P_PRODUCT_ID);
EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
END PROC_RECEIVE_STOCK;
/

--- 7. STOCK_TRANSACTION 
CREATE OR REPLACE PROCEDURE HRDB.PROC_ISSUE_STOCK (
    P_PRODUCT_ID     IN NUMBER,
    P_WAREHOUSE_ID   IN NUMBER,
    P_QTY            IN NUMBER,
    P_REFERENCE_TYPE IN VARCHAR2 DEFAULT 'MANUAL',
    P_REFERENCE_ID   IN NUMBER DEFAULT NULL
)
AS
    V_CURRENT_QTY NUMBER;
BEGIN
    IF P_QTY <= 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Quantity must be positive.');
    END IF;

    SELECT QUANTITY_ON_HAND INTO V_CURRENT_QTY FROM HRDB.STOCK
    WHERE PRODUCT_ID = P_PRODUCT_ID AND WAREHOUSE_ID = P_WAREHOUSE_ID
    FOR UPDATE;

    IF V_CURRENT_QTY < P_QTY THEN
        RAISE_APPLICATION_ERROR(-20003,
            'Insufficient stock. Available: ' || V_CURRENT_QTY || ', Requested: ' || P_QTY);
    END IF;

    UPDATE HRDB.STOCK
    SET QUANTITY_ON_HAND = QUANTITY_ON_HAND - P_QTY, LAST_UPDATED = SYSDATE
    WHERE PRODUCT_ID = P_PRODUCT_ID AND WAREHOUSE_ID = P_WAREHOUSE_ID;

    INSERT INTO HRDB.STOCK_TRANSACTION (
        PRODUCT_ID, WAREHOUSE_ID, TRANSACTION_TYPE, QUANTITY,
        TRANSACTION_DATE, REFERENCE_TYPE, REFERENCE_ID
    ) VALUES (
        P_PRODUCT_ID, P_WAREHOUSE_ID, 'OUT', P_QTY, SYSDATE, P_REFERENCE_TYPE, P_REFERENCE_ID
    );

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Issued ' || P_QTY || ' units of product ' || P_PRODUCT_ID);
EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
END PROC_ISSUE_STOCK;
/

--- 8. PURCHASE_ORDER
CREATE OR REPLACE PROCEDURE HRDB.PROC_CREATE_PURCHASE_ORDER (
    P_SUPPLIER_ID    IN  NUMBER,
    P_WAREHOUSE_ID   IN  NUMBER,
    P_EXPECTED_DAYS  IN  NUMBER DEFAULT 7,
    P_PO_ID          OUT NUMBER
)
AS
BEGIN
    INSERT INTO HRDB.PURCHASE_ORDER (
        PO_NUMBER, SUPPLIER_ID, WAREHOUSE_ID, ORDER_DATE, EXPECTED_DATE, STATUS, TOTAL_AMOUNT
    ) VALUES (
        'PO-' || HRDB.PO_NUMBER_SEQ.NEXTVAL, P_SUPPLIER_ID, P_WAREHOUSE_ID,
        SYSDATE, SYSDATE + P_EXPECTED_DAYS, 'PENDING', 0
    ) RETURNING PO_ID INTO P_PO_ID;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Purchase Order created, ID: ' || P_PO_ID);
END PROC_CREATE_PURCHASE_ORDER;
/

--- 9. PURCHASE_ORDER_DETAIL 
CREATE OR REPLACE PROCEDURE HRDB.PROC_ADD_PO_DETAIL (
    P_PO_ID      IN NUMBER,
    P_PRODUCT_ID IN NUMBER,
    P_QTY        IN NUMBER,
    P_UNIT_PRICE IN NUMBER
)
AS
BEGIN
    INSERT INTO HRDB.PURCHASE_ORDER_DETAIL (PO_ID, PRODUCT_ID, ORDERED_QTY, UNIT_PRICE)
    VALUES (P_PO_ID, P_PRODUCT_ID, P_QTY, P_UNIT_PRICE);

    UPDATE HRDB.PURCHASE_ORDER
    SET TOTAL_AMOUNT = NVL(TOTAL_AMOUNT, 0) + (P_QTY * P_UNIT_PRICE)
    WHERE PO_ID = P_PO_ID;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Added ' || P_QTY || ' units of product ' || P_PRODUCT_ID || ' to PO ' || P_PO_ID);
END PROC_ADD_PO_DETAIL;
/

